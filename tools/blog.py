"""ブログ記事執筆ツール。"""

from __future__ import annotations

from config import TONES

from .base import Field, Tool, compose, section

SYSTEM = """あなたはSEOと読者体験の両方に強い日本語ブログライターです。
検索エンジンではなく検索した人に向けて書き、その結果として上位に立つ記事を作ります。

## 検索意図をつかむ
- テーマから「読者はその語で検索して何を解決したいのか」をまず推定し、記事全体でそれに答える。
- 読者が次に抱く疑問（「で、いくらかかる？」「自分にもできる？」「他と何が違う？」）に先回りして答える。
- 一般論で埋めない。手順・数値・具体例・判断基準のいずれかを必ず含める。

## タイトル（1行目の # 見出し）
- 全角32文字前後。主要キーワードはできるだけ前方に置く。
- 「読むと何が得られるか」を明示する。数字・年・対象読者のいずれかを入れると強い。
- 煽り表現や体言止めの羅列にしない。読んで意味の通る一文にする。

## キーワードの扱い
- 指定キーワードは、タイトル・冒頭200文字・H2 の少なくとも1つ・まとめ に自然に配置する。
- 不自然な繰り返し（詰め込み）はしない。共起語・言い換え・関連語を織り交ぜて厚みを出す。
- キーワードのために日本語を崩さない。読みやすさを優先する。

## 構成
- 出力は Markdown。H2(##) と H3(###) で構造化し、リード文には見出しを付けない。
- 冒頭200文字以内で「この記事を読むと何が得られるか」と結論の要点を先に示す（結論→理由→具体例→結論）。
- H2 は、目次として並べて読むだけで記事の全体像が分かる文にする。検索されうる語や疑問文の形を意識する。
- 1つの H2 につき論点は1つ。話題が2つになったら H2 を分ける。
- 記事後半に「よくある質問」セクションを置き、関連する疑問3つ前後にそれぞれ2〜3文で答える。
- 最後に「まとめ」セクションを置き、要点を箇条書きで再掲したうえで、行動を促す一文で締める。

## 文章
- 1段落は3文以内。1文は60文字を目安に短く切る。
- 専門用語は初出時に一言で補足する。
- 箇条書き・表を適切に混ぜ、読み飛ばしても要点が伝わるようにする。比較・条件・手順は表か番号付きリストにする。
- 「〜と言えるでしょう」「いかがでしたか」など中身のない定型句は書かない。
- 素材として与えられた体験・データは必ず本文に織り込む。一次情報は記事の価値そのもの。
- 数値・固有名詞・年月は素材にないものを創作しない。不確かなものには「[要確認]」を付ける。

## 分量
- 指定文字数の ±10% に収める。見出しだけ増やして本文が薄くなる書き方はしない。
"""


def build(v: dict) -> str:
    return compose(
        "以下の条件でブログ記事を執筆してください。",
        section("テーマ", v["topic"]),
        section("想定読者", v.get("audience")),
        section("記事の狙い", v.get("goal")),
        section("必ず含めるキーワード", v.get("keywords")),
        section("盛り込みたい素材・事実", v.get("material")),
        section("文体トーン", v.get("tone")),
        section("目安の文字数", f"{v.get('length')}文字程度"),
        section("見出し構成", "指定なし（最適な構成を提案する）" if not v.get("outline") else v["outline"]),
        "## 出力形式\n"
        "1行目に記事タイトル（# 見出し1）を書き、続けて本文を書いてください。"
        + (
            "\n本文の最後に「メタディスクリプション案」として、主要キーワードを前半に含む "
            "120文字以内の説明文を付けてください。記事の要約ではなく、クリックしたくなる誘導文にします。"
            if v.get("meta") else ""
        ),
    )


TOOL = Tool(
    key="blog",
    name="ブログ記事執筆",
    icon="📝",
    category="つくる",
    description="テーマと読者像から、構成付きのブログ記事をまるごと書き上げます。",
    system_prompt=SYSTEM,
    temperature=0.8,
    default_length="長め",
    submit_label="記事を書く",
    fields=[
        Field("topic", "テーマ・タイトル案", "text", required=True,
              placeholder="例: 個人開発者がStreamlitで社内ツールを作るべき理由"),
        Field("audience", "想定読者", "text", row=1,
              placeholder="例: Pythonは書けるがWebは苦手なエンジニア"),
        Field("goal", "記事の狙い", "text", row=1,
              placeholder="例: Streamlitを試してもらう"),
        Field("tone", "文体トーン", "select", options=TONES, default="フレンドリーな敬体（です・ます）", row=2),
        Field("length", "目安文字数", "number", default=2500, row=2),
        Field("keywords", "キーワード（カンマ区切り）", "text",
              placeholder="例: Streamlit, 業務効率化, Python"),
        Field("material", "盛り込みたい素材・事実・体験", "textarea", height=140,
              placeholder="自分の体験、data、引用したい事実などを箇条書きで。空欄でも可。"),
        Field("outline", "見出し構成（任意）", "textarea", height=120,
              placeholder="決まっていれば H2 レベルで列挙。空欄なら AI が構成を考えます。"),
        Field("meta", "メタディスクリプション案も出す", "checkbox", default=True),
    ],
    build_prompt=build,
)
